export function formatMessage(template: string, values: Record<string, string | number>) {
  return Object.entries(values).reduce((message, [key, value]) => message.replaceAll(`{${key}}`, String(value)), template);
}

export function t(locale: AppLocale) {
  if (locale === "en-US") return deepMerge(dictionary["pt-BR"], dictionary["en-US"], englishOverrides) as typeof dictionary["pt-BR"];
  if (locale === "es-ES") return deepMerge(dictionary["pt-BR"], dictionary["es-ES"], spanishOverrides) as typeof dictionary["pt-BR"];
  return dictionary["pt-BR"];
}

function deepMerge(...objects: Array<Record<string, unknown>>): Record<string, unknown> {
  const result: Record<string, unknown> = {};
  for (const object of objects) {
    for (const [key, value] of Object.entries(object)) {
      const current = result[key];
      if (isPlainObject(current) && isPlainObject(value)) {
        result[key] = deepMerge(current, value);
      } else {
        result[key] = value;
      }
    }
  }
  return result;
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}
